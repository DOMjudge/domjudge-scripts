#!/bin/bash
# Prepare the ansible tree for the Vagrant test bed: SSH key, inventory,
# group_vars. Refuses to overwrite files it did not generate itself, so a
# real `hosts` / secret.yml is never clobbered.
set -euo pipefail
cd "$(dirname "$0")/.." || exit 1

MARK='generated-by: provision-contest/ansible/test'
GV=group_vars/onprem

safe_to_write() { [ ! -e "$1" ] || grep -q "$MARK" "$1"; }

for f in hosts $GV/all.yml $GV/secret.yml; do
    safe_to_write "$f" || { echo "$f exists and was not generated by $0; move it away first." >&2; exit 1; }
done

# DJ_BRANCH=<tag or commit> pins the DOMjudge version, so that new upstream commits
# don't trigger rebuilds while testing for idempotency. A pin is kept when this
# script is run again; DJ_BRANCH=main removes it.
# VARIANT=icpc: the machines run the ICPC contest image (GRAPHICAL=true to also
# exercise the desktop related tasks); the default is a stock Ubuntu image.
graphical=${GRAPHICAL:-false}
case "$graphical" in
    true|false) ;;
    *) echo "GRAPHICAL must be true or false." >&2; exit 1 ;;
esac
case "${VARIANT:-}" in
    icpc) icpc=true; aws=false ;;
    "")   icpc=false; aws=true
          [ "$graphical" = false ] || { echo "GRAPHICAL=true needs VARIANT=icpc (the cloud image has no desktop)." >&2; exit 1; } ;;
    *)    echo "Unknown VARIANT '$VARIANT': use VARIANT=icpc or leave it unset." >&2; exit 1 ;;
esac
if [ -z "${DJ_BRANCH:-}" ] && [ -e $GV/all.yml ]; then
    DJ_BRANCH=$(sed -n 's/^DJ_BRANCH: *//p' $GV/all.yml)
fi

make roles/ssh/files/id_ed25519

# A link, not a copy, so the Vagrantfile and ansible always see the same machines.
ln -sfn test/hosts.vagrant hosts

# One domserver and no keepalived VIP: judgehosts talk to the domserver directly.
domserver_ip=$(awk '/^[[:space:]]*([#;]|$)/ { next } /^[[:space:]]*\[/ { g = $1 }
                    g == "[domserver]" && /ansible_host=/ { sub(/.*ansible_host=/, ""); print $1; exit }' hosts)
[ -n "$domserver_ip" ] || { echo "No domserver with ansible_host= in test/hosts.vagrant." >&2; exit 1; }

{ echo "# $MARK"
  sed -e "s/^DOMSERVER_IP:.*/DOMSERVER_IP: $domserver_ip/" \
      -e "s/^ICPC_IMAGE:.*/ICPC_IMAGE: $icpc/" \
      -e "s/^AWS:.*/AWS: $aws/" \
      -e "s/^GRAPHICAL:.*/GRAPHICAL: $graphical/" \
      ${DJ_BRANCH:+-e "s|^DJ_BRANCH:.*|DJ_BRANCH: $DJ_BRANCH|"} $GV/all.yml.example
} > $GV/all.yml

# Same job as generate_passwords.py, without the xkcdpass dependency. Keep an
# existing file: the passwords are already in the databases of provisioned VMs.
if [ ! -e $GV/secret.yml ]; then
python3 - "$MARK" <<'PY' > $GV/secret.yml
import re, secrets, sys
print("# " + sys.argv[1])
for line in open("group_vars/onprem/secret.yml.example"):
    print(re.sub(r"\{[^}]*\}", lambda m: secrets.token_urlsafe(18), line), end="")
PY
fi

echo "Done. Next: see test/README.md (vagrant up, snapshot, make domserver judgehost, test/verify.sh)."
